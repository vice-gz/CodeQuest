-- ============================================================
-- CodeQuest — Avance 2.2: roles (super_root / profesor / estudiante),
-- clases, auditoría y endurecimiento de políticas.
-- Ejecutar en Supabase -> SQL Editor DESPUÉS de avance2.sql.
-- Es idempotente (se puede volver a ejecutar) y va en una transacción:
-- si algo falla, no queda nada a medias.
--
-- Cambios importantes respecto a la especificación original:
--  * super_root cuenta como admin en TODAS las comprobaciones (cq_es_admin).
--  * Los profesores YA NO ven a todos los usuarios: solo a sus alumnos
--    (las políticas "Profesores y admins ven ..." pasan a ser solo admin).
--  * Crear clase, unirse a una clase, cambiar rol, resetear y eliminar se
--    hacen por funciones del servidor (validan reglas y registran auditoría);
--    no hay INSERT directo en clases/inscripciones desde el navegador.
--  * Un trigger impide que NADIE toque a un super_root desde la API.
-- ============================================================

begin;

-- ---------- 0) Rol super_root permitido ----------
do $$
declare r record;
begin
  for r in
    select conname from pg_constraint
    where conrelid = 'public.perfiles'::regclass and contype = 'c'
      and pg_get_constraintdef(oid) ilike '%rol%'
  loop
    execute format('alter table public.perfiles drop constraint %I', r.conname);
  end loop;
end $$;

alter table public.perfiles
  add constraint perfiles_rol_check
  check (rol in ('estudiante', 'profesor', 'admin', 'super_root'));

-- ---------- 1) Tablas nuevas ----------
create table if not exists public.clases (
  id uuid primary key default gen_random_uuid(),
  profesor_id uuid not null references auth.users(id) on delete cascade,
  nombre text not null,
  codigo_acceso text unique not null,
  dominio_permitido text default null,
  created_at timestamptz default now()
);

create table if not exists public.inscripciones (
  id uuid primary key default gen_random_uuid(),
  clase_id uuid not null references public.clases(id) on delete cascade,
  estudiante_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz default now(),
  unique (clase_id, estudiante_id)
);

create table if not exists public.auditoria (
  id bigint generated by default as identity primary key,
  admin_id uuid references auth.users(id) on delete set null,
  accion text not null,
  objetivo_id uuid,
  detalles jsonb,
  created_at timestamptz default now()
);

-- Registra que el "registro inicial" (rol pedido y código de clase) ya se aplicó.
create table if not exists public.registro_inicial (
  user_id uuid primary key references auth.users(id) on delete cascade,
  aplicado_at timestamptz default now()
);

create index if not exists idx_clases_profesor on public.clases (profesor_id);
create index if not exists idx_inscripciones_estudiante on public.inscripciones (estudiante_id);
create index if not exists idx_auditoria_fecha on public.auditoria (created_at desc);

alter table public.clases enable row level security;
alter table public.inscripciones enable row level security;
alter table public.auditoria enable row level security;
alter table public.registro_inicial enable row level security; -- sin políticas: solo funciones

-- ---------- 2) Funciones de apoyo para RLS ----------
create or replace function public.cq_rol_actual()
returns text language sql stable security definer set search_path = public as $$
  select rol::text from public.perfiles where user_id = auth.uid();
$$;

-- admin Y super_root
create or replace function public.cq_es_admin()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.perfiles
                 where user_id = auth.uid() and rol in ('admin', 'super_root'));
$$;

create or replace function public.cq_es_super_root()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.perfiles where user_id = auth.uid() and rol = 'super_root');
$$;

create or replace function public.cq_es_staff()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.perfiles
                 where user_id = auth.uid() and rol in ('profesor', 'admin', 'super_root'));
$$;

create or replace function public.cq_es_mi_alumno(p_estudiante_id uuid)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from public.inscripciones i
    join public.clases c on c.id = i.clase_id
    where c.profesor_id = auth.uid() and i.estudiante_id = p_estudiante_id
  );
$$;

revoke all on function public.cq_rol_actual(), public.cq_es_admin(), public.cq_es_super_root(),
  public.cq_es_staff(), public.cq_es_mi_alumno(uuid) from public, anon;
grant execute on function public.cq_rol_actual(), public.cq_es_admin(), public.cq_es_super_root(),
  public.cq_es_staff(), public.cq_es_mi_alumno(uuid) to authenticated;

-- ---------- 3) Candado de roles (trigger) ----------
-- Desde la API nadie puede tocar el rol de un super_root, ni cambiar su propio
-- rol, ni crear/quitar admins salvo un super_root. Desde el SQL Editor
-- (sin sesión de usuario) todo está permitido: así se crea el super_root.
create or replace function public.cq_proteger_roles()
returns trigger language plpgsql security definer set search_path = public as $$
declare v_actual text;
begin
  if new.rol is not distinct from old.rol then return new; end if;
  if auth.uid() is null or current_setting('cq.bypass_roles', true) = '1' then return new; end if;

  v_actual := public.cq_rol_actual();
  if v_actual not in ('admin', 'super_root') then
    raise exception 'No autorizado' using errcode = '42501';
  end if;
  if old.rol = 'super_root' or new.rol = 'super_root' then
    raise exception 'Un usuario Super Root no puede ser modificado desde aquí.' using errcode = 'P0001';
  end if;
  if new.user_id = auth.uid() then
    raise exception 'No puedes cambiar tu propio rol.' using errcode = 'P0001';
  end if;
  if (old.rol = 'admin' or new.rol = 'admin') and v_actual <> 'super_root' then
    raise exception 'Solo un Super Root puede crear o quitar administradores.' using errcode = 'P0001';
  end if;
  return new;
end;
$$;

drop trigger if exists cq_proteger_roles on public.perfiles;
create trigger cq_proteger_roles
  before update of rol on public.perfiles
  for each row execute function public.cq_proteger_roles();

-- ---------- 4) Políticas ----------
-- 4.1 Quitar las políticas que daban acceso total a profesores o escritura
--     directa a admins (ahora se hace por funciones con reglas y auditoría).
drop policy if exists "Profesores y admins ven todos los perfiles" on public.perfiles;
drop policy if exists "Profesores y admins ven todas las ejecuciones" on public.ejecuciones;
drop policy if exists "Profesores y admins ven todas las fases" on public.progreso_fases;
drop policy if exists "Profesores y admins ven todo el progreso" on public.progreso_jugador;
drop policy if exists "Admins editan cualquier perfil" on public.perfiles;
drop policy if exists "Admins borran fases de cualquiera" on public.progreso_fases;
drop policy if exists "Admins actualizan cualquier progreso" on public.progreso_jugador;

-- Un usuario solo puede crear su propio perfil como estudiante.
drop policy if exists "Usuarios insertan su propio perfil" on public.perfiles;
create policy "Usuarios insertan su propio perfil" on public.perfiles
  for insert to authenticated
  with check ((select auth.uid()) = user_id and rol = 'estudiante');

-- 4.2 Admins (y super_root): lectura total
drop policy if exists "Admins ven todos los perfiles" on public.perfiles;
create policy "Admins ven todos los perfiles" on public.perfiles
  for select to authenticated using (public.cq_es_admin());

drop policy if exists "Admins ven todas las ejecuciones" on public.ejecuciones;
create policy "Admins ven todas las ejecuciones" on public.ejecuciones
  for select to authenticated using (public.cq_es_admin());

drop policy if exists "Admins ven todas las fases" on public.progreso_fases;
create policy "Admins ven todas las fases" on public.progreso_fases
  for select to authenticated using (public.cq_es_admin());

drop policy if exists "Admins ven todo el progreso" on public.progreso_jugador;
create policy "Admins ven todo el progreso" on public.progreso_jugador
  for select to authenticated using (public.cq_es_admin());

-- 4.3 Profesores: solo sus alumnos
drop policy if exists "Profesores ven a sus alumnos" on public.perfiles;
create policy "Profesores ven a sus alumnos" on public.perfiles
  for select to authenticated using (public.cq_es_mi_alumno(user_id));

drop policy if exists "Profesores ven progreso de sus alumnos" on public.progreso_jugador;
create policy "Profesores ven progreso de sus alumnos" on public.progreso_jugador
  for select to authenticated using (public.cq_es_mi_alumno(user_id));

drop policy if exists "Profesores ven fases de sus alumnos" on public.progreso_fases;
create policy "Profesores ven fases de sus alumnos" on public.progreso_fases
  for select to authenticated using (public.cq_es_mi_alumno(user_id));

drop policy if exists "Profesores ven ejecuciones de sus alumnos" on public.ejecuciones;
create policy "Profesores ven ejecuciones de sus alumnos" on public.ejecuciones
  for select to authenticated using (public.cq_es_mi_alumno(user_id));

-- 4.4 Clases e inscripciones (el INSERT se hace solo por funciones)
drop policy if exists "Profesores ven sus propias clases" on public.clases;
create policy "Profesores ven sus propias clases" on public.clases
  for select to authenticated using (profesor_id = auth.uid() or public.cq_es_admin());

drop policy if exists "Profesores editan sus clases" on public.clases;
create policy "Profesores editan sus clases" on public.clases
  for update to authenticated
  using (profesor_id = auth.uid()) with check (profesor_id = auth.uid());

drop policy if exists "Profesores borran sus clases" on public.clases;
create policy "Profesores borran sus clases" on public.clases
  for delete to authenticated using (profesor_id = auth.uid() or public.cq_es_admin());

drop policy if exists "Alumnos ven sus inscripciones" on public.inscripciones;
create policy "Alumnos ven sus inscripciones" on public.inscripciones
  for select to authenticated using (estudiante_id = auth.uid());

drop policy if exists "Profesores ven inscripciones de sus clases" on public.inscripciones;
create policy "Profesores ven inscripciones de sus clases" on public.inscripciones
  for select to authenticated using (
    exists (select 1 from public.clases c where c.id = clase_id and c.profesor_id = auth.uid())
    or public.cq_es_admin()
  );

-- 4.5 Auditoría: solo la leen admins; nadie la escribe desde la API
drop policy if exists "Solo staff ve auditoria" on public.auditoria;
create policy "Solo staff ve auditoria" on public.auditoria
  for select to authenticated using (public.cq_es_admin());

-- ---------- 5) Funciones: clases ----------
create or replace function public.crear_clase(p_nombre text, p_dominio text default null)
returns public.clases
language plpgsql security definer set search_path = public as $$
declare
  v_nombre text := trim(coalesce(p_nombre, ''));
  v_dominio text := nullif(regexp_replace(lower(trim(coalesce(p_dominio, ''))), '^@', ''), '');
  v_alfabeto constant text := 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
  v_codigo text;
  v_fila public.clases;
  v_intentos int := 0;
begin
  if public.cq_rol_actual() not in ('profesor', 'admin', 'super_root') then
    raise exception 'No autorizado' using errcode = '42501';
  end if;
  if length(v_nombre) < 2 or length(v_nombre) > 80 then
    raise exception 'Escribe un nombre de clase (2 a 80 caracteres).' using errcode = 'P0001';
  end if;
  if v_dominio is not null and v_dominio !~ '^[a-z0-9.-]+\.[a-z]{2,}$' then
    raise exception 'El dominio permitido no es válido (ejemplo: pachuca.tecnm.mx).' using errcode = 'P0001';
  end if;

  loop
    select string_agg(substr(v_alfabeto, 1 + floor(random() * length(v_alfabeto))::int, 1), '')
      into v_codigo from generate_series(1, 6);
    begin
      insert into public.clases (profesor_id, nombre, codigo_acceso, dominio_permitido)
      values (auth.uid(), v_nombre, v_codigo, v_dominio)
      returning * into v_fila;
      return v_fila;
    exception when unique_violation then
      v_intentos := v_intentos + 1;
      if v_intentos > 10 then
        raise exception 'No se pudo generar un código único. Inténtalo de nuevo.' using errcode = 'P0001';
      end if;
    end;
  end loop;
end;
$$;

create or replace function public.unirse_a_clase(p_codigo text)
returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_uid uuid := auth.uid();
  v_clase public.clases;
  v_dominio_correo text;
begin
  if v_uid is null then raise exception 'Inicia sesión primero.' using errcode = '42501'; end if;
  if public.cq_rol_actual() is distinct from 'estudiante' then
    raise exception 'Solo los alumnos pueden unirse a una clase.' using errcode = 'P0001';
  end if;

  select * into v_clase from public.clases where codigo_acceso = upper(trim(coalesce(p_codigo, '')));
  if not found then
    raise exception 'El código de clase no es válido.' using errcode = 'P0001';
  end if;

  select split_part(lower(email), '@', 2) into v_dominio_correo from auth.users where id = v_uid;
  if v_clase.dominio_permitido is not null
     and v_dominio_correo <> v_clase.dominio_permitido
     and v_dominio_correo not like '%.' || v_clase.dominio_permitido then
    raise exception 'Tu correo no pertenece al dominio permitido por esta clase (@%).', v_clase.dominio_permitido
      using errcode = 'P0001';
  end if;

  insert into public.inscripciones (clase_id, estudiante_id)
  values (v_clase.id, v_uid) on conflict do nothing;

  return jsonb_build_object('clase_id', v_clase.id, 'nombre', v_clase.nombre);
end;
$$;

create or replace function public.mis_clases()
returns table (clase_id uuid, nombre text, profesor_nombre text, inscrito_en timestamptz)
language sql stable security definer set search_path = public as $$
  select c.id, c.nombre, p.nombre::text, i.created_at
  from public.inscripciones i
  join public.clases c on c.id = i.clase_id
  left join public.perfiles p on p.user_id = c.profesor_id
  where i.estudiante_id = auth.uid()
  order by i.created_at desc;
$$;

create or replace function public.salir_de_clase(p_clase_id uuid)
returns void language sql security definer set search_path = public as $$
  delete from public.inscripciones where clase_id = p_clase_id and estudiante_id = auth.uid();
$$;

create or replace function public.profesor_alumnos_clase(p_clase_id uuid)
returns table (
  estudiante_id uuid, nombre text, email text,
  mundo_actual int, nivel_actual int, experiencia int,
  ultima_actividad timestamptz, inscrito_en timestamptz
)
language sql stable security definer set search_path = public as $$
  select i.estudiante_id, p.nombre::text, u.email::text,
         pj.mundo_actual::int, pj.nivel_actual::int, pj.experiencia::int,
         greatest(pj.updated_at,
                  (select max(e.created_at) from public.ejecuciones e where e.user_id = i.estudiante_id)),
         i.created_at
  from public.inscripciones i
  join public.clases c on c.id = i.clase_id
  join public.perfiles p on p.user_id = i.estudiante_id
  join auth.users u on u.id = i.estudiante_id
  left join public.progreso_jugador pj on pj.user_id = i.estudiante_id
  where i.clase_id = p_clase_id
    and (c.profesor_id = auth.uid() or public.cq_es_admin())
  order by p.nombre;
$$;

-- ---------- 6) Registro inicial (rol pedido + código de clase) ----------
-- El navegador pide el rol en user_metadata al registrarse; aquí se aplica UNA
-- sola vez. El rol 'profesor' lo declara cada persona al registrarse; el
-- 'admin' y el 'super_root' nunca se pueden pedir por esta vía.
create or replace function public.aplicar_registro()
returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_uid uuid := auth.uid();
  v_meta jsonb;
  v_rol_pedido text;
  v_codigo text;
  v_rol text;
  v_clase jsonb := null;
  v_aviso text := null;
begin
  if v_uid is null then raise exception 'Inicia sesión primero.' using errcode = '42501'; end if;

  if exists (select 1 from public.registro_inicial where user_id = v_uid) then
    return jsonb_build_object('rol', public.cq_rol_actual(), 'aplicado', false);
  end if;
  insert into public.registro_inicial (user_id) values (v_uid);

  select raw_user_meta_data into v_meta from auth.users where id = v_uid;
  v_rol_pedido := lower(coalesce(v_meta ->> 'rol_solicitado', ''));
  v_codigo := upper(trim(coalesce(v_meta ->> 'codigo_clase', '')));
  v_rol := public.cq_rol_actual();

  if v_rol_pedido = 'profesor' and v_rol = 'estudiante' then
    perform set_config('cq.bypass_roles', '1', true);
    update public.perfiles set rol = 'profesor' where user_id = v_uid and rol = 'estudiante';
    perform set_config('cq.bypass_roles', '0', true);
    v_rol := 'profesor';
  elsif v_rol = 'estudiante' and v_codigo <> '' then
    begin
      v_clase := public.unirse_a_clase(v_codigo);
    exception when others then
      v_aviso := sqlerrm;
    end;
  end if;

  return jsonb_build_object('rol', v_rol, 'aplicado', true, 'clase', v_clase, 'aviso', v_aviso);
end;
$$;

-- ---------- 7) Funciones de administración (con auditoría) ----------
create or replace function public.admin_cambiar_rol(p_user_id uuid, p_rol text)
returns void language plpgsql security definer set search_path = public as $$
declare
  v_actual text := public.cq_rol_actual();
  v_objetivo text;
  v_nombre text;
begin
  if v_actual not in ('admin', 'super_root') then
    raise exception 'No autorizado' using errcode = '42501';
  end if;
  if p_rol not in ('estudiante', 'profesor', 'admin') then
    raise exception 'Rol no válido.' using errcode = 'P0001';
  end if;
  select rol, nombre into v_objetivo, v_nombre from public.perfiles where user_id = p_user_id;
  if v_objetivo is null then
    raise exception 'Usuario no encontrado.' using errcode = 'P0001';
  end if;
  if v_objetivo = p_rol then return; end if;

  -- El trigger cq_proteger_roles vuelve a validar estas mismas reglas.
  update public.perfiles set rol = p_rol where user_id = p_user_id;

  insert into public.auditoria (admin_id, accion, objetivo_id, detalles)
  values (auth.uid(), 'cambiar_rol', p_user_id,
          jsonb_build_object('nombre', v_nombre, 'rol_anterior', v_objetivo, 'rol_nuevo', p_rol));
end;
$$;

create or replace function public.admin_resetear_progreso(p_user_id uuid)
returns void language plpgsql security definer set search_path = public as $$
declare
  v_actual text := public.cq_rol_actual();
  v_objetivo text;
  v_nombre text;
begin
  if v_actual not in ('admin', 'super_root') then
    raise exception 'No autorizado' using errcode = '42501';
  end if;
  select rol, nombre into v_objetivo, v_nombre from public.perfiles where user_id = p_user_id;
  if v_objetivo is null then raise exception 'Usuario no encontrado.' using errcode = 'P0001'; end if;
  if v_objetivo = 'super_root' then
    raise exception 'Un usuario Super Root no puede ser modificado desde aquí.' using errcode = 'P0001';
  end if;
  if v_objetivo = 'admin' and v_actual <> 'super_root' then
    raise exception 'Solo un Super Root puede modificar a otro administrador.' using errcode = 'P0001';
  end if;

  delete from public.progreso_fases where user_id = p_user_id;
  update public.progreso_jugador
     set mundo_actual = 1, nivel_actual = 1, experiencia = 0 where user_id = p_user_id;
  if not found then
    insert into public.progreso_jugador (user_id, mundo_actual, nivel_actual, experiencia)
    values (p_user_id, 1, 1, 0);
  end if;

  insert into public.auditoria (admin_id, accion, objetivo_id, detalles)
  values (auth.uid(), 'resetear_progreso', p_user_id, jsonb_build_object('nombre', v_nombre, 'rol', v_objetivo));
end;
$$;

-- Sustituye a la versión del Avance 2: añade candado de super_root y auditoría.
create or replace function public.admin_eliminar_usuario(p_user_id uuid)
returns void language plpgsql security definer set search_path = public as $$
declare
  v_actual text := public.cq_rol_actual();
  v_objetivo text;
  v_nombre text;
  v_email text;
begin
  if v_actual not in ('admin', 'super_root') then
    raise exception 'No autorizado' using errcode = '42501';
  end if;
  if p_user_id = auth.uid() then
    raise exception 'No puedes eliminar tu propia cuenta.' using errcode = 'P0001';
  end if;

  select rol, nombre into v_objetivo, v_nombre from public.perfiles where user_id = p_user_id;
  select email into v_email from auth.users where id = p_user_id;

  if v_objetivo = 'super_root' then
    raise exception 'Un usuario Super Root no puede ser eliminado desde la interfaz web.' using errcode = 'P0001';
  end if;
  if v_objetivo = 'admin' and v_actual <> 'super_root' then
    raise exception 'Solo un Super Root puede eliminar a otro administrador.' using errcode = 'P0001';
  end if;

  insert into public.auditoria (admin_id, accion, objetivo_id, detalles)
  values (auth.uid(), 'eliminar_usuario', p_user_id,
          jsonb_build_object('nombre', v_nombre, 'email', v_email, 'rol_objetivo', v_objetivo));

  delete from public.ejecuciones      where user_id = p_user_id;
  delete from public.progreso_fases   where user_id = p_user_id;
  delete from public.progreso_jugador where user_id = p_user_id;
  delete from public.inscripciones    where estudiante_id = p_user_id;
  delete from public.perfiles         where user_id = p_user_id;
  delete from auth.users              where id = p_user_id; -- si era profesor, se borran también sus clases
end;
$$;

create or replace function public.admin_auditoria(p_limite int default 50)
returns table (
  id bigint, fecha timestamptz, admin_nombre text, admin_email text,
  accion text, objetivo_id uuid, detalles jsonb
)
language sql stable security definer set search_path = public as $$
  select a.id, a.created_at, p.nombre::text, u.email::text, a.accion, a.objetivo_id, a.detalles
  from public.auditoria a
  left join public.perfiles p on p.user_id = a.admin_id
  left join auth.users u on u.id = a.admin_id
  where public.cq_es_admin()
  order by a.created_at desc
  limit least(greatest(coalesce(p_limite, 50), 1), 200);
$$;

-- ---------- 8) Alumno: borrar su propio progreso ----------
create or replace function public.alumno_borrar_progreso()
returns void language plpgsql security definer set search_path = public as $$
begin
  if public.cq_rol_actual() not in ('estudiante', 'profesor') then
    raise exception 'Esta acción no está disponible para tu rol.' using errcode = 'P0001';
  end if;

  delete from public.ejecuciones      where user_id = auth.uid();
  delete from public.progreso_fases   where user_id = auth.uid();
  delete from public.progreso_jugador where user_id = auth.uid();

  insert into public.progreso_jugador (user_id, mundo_actual, nivel_actual, experiencia)
  values (auth.uid(), 1, 1, 0);
end;
